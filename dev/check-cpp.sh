#!/bin/sh
# Check C++ files in src/: formatting (clang-format), compiler warnings and
# static analysis (clang-tidy, .clang-tidy).
#
# Usage: dev/check-cpp.sh [file ...]
# Without files, checks the C++ files changed against master (including
# untracked ones). A changed header also checks the .cpp files including it.
# Exits non-zero if any check reports a problem.
set -u
cd "$(dirname "$0")/.." || exit 1

if [ $# -eq 0 ]; then
  set -- $({
    git diff --name-only master -- 'src/*.cpp' 'src/*.hpp'
    git ls-files --others --exclude-standard -- 'src/*.cpp' 'src/*.hpp'
  } | sort -u)
fi

files=""
sources=""
for f in "$@"; do
  # Generated by devtools::document(), deleted files
  [ "$f" = "src/cpp11.cpp" ] && continue
  [ -f "$f" ] || continue
  files="$files $f"
  case "$f" in
    *.cpp) sources="$sources $f" ;;
    *.hpp)
      # .cpp files that include the header
      for s in src/*.cpp; do
        [ "$s" = "src/cpp11.cpp" ] && continue
        grep -q "$(basename "$f")" "$s" && sources="$sources $s"
      done
      ;;
  esac
done
sources=$(printf '%s\n' $sources | sort -u)

if [ -z "$files" ]; then
  echo "No changed C++ files."
  exit 0
fi

r_include=$(Rscript -e 'cat(R.home("include"))')
cpp11_include=$(Rscript -e 'cat(system.file("include", package = "cpp11"))')
# System includes: warnings in R and cpp11 headers are not ours
flags="-std=c++20 -Isrc -isystem $r_include -isystem $cpp11_include"
status=0

echo "== clang-format"
clang-format --dry-run --Werror $files || status=1

echo "== compiler warnings"
cxx=${CXX:-clang++}
for s in $sources; do
  $cxx $flags -fsyntax-only -Wall -Wextra -Wpedantic -Wshadow -Werror "$s" ||
    status=1
done

echo "== clang-tidy"
tidy=$(command -v clang-tidy || echo /opt/homebrew/opt/llvm/bin/clang-tidy)
if [ -x "$tidy" ]; then
  # Homebrew's LLVM may pick an old macOS SDK; use the current one
  tidy_flags=$flags
  if command -v xcrun > /dev/null; then
    tidy_flags="$flags -isysroot $(xcrun --show-sdk-path)"
  fi
  for s in $sources; do
    "$tidy" --quiet --warnings-as-errors='*' "$s" -- $tidy_flags || status=1
  done
else
  echo "clang-tidy not found (macOS: brew install llvm)"
  status=1
fi

exit $status
